#!/bin/bash
set -e

CONFIG_SRC="/var/www/html/deploy/docker/config/config.inc.docker.php"
CONFIG_DST="/var/www/html/includes/config.inc.php"
STATE_SRC="/var/www/html/includes/class.State-sample.inc.php"
STATE_DST="/var/www/html/includes/class.State.inc.php"
CONFIG_TEST_SRC="/var/www/html/deploy/docker/config/config-test.inc.docker.php"
CONFIG_TEST_DST="/var/www/html/includes/config-test.inc.php"

# Drop in config.inc.php from the Docker template unless a real one is already present
if [ ! -f "$CONFIG_DST" ]; then
    cp "$CONFIG_SRC" "$CONFIG_DST"
    echo "[entrypoint] Installed config.inc.php from Docker template"
fi

# Drop in class.State.inc.php from the sample unless a real one is already present
if [ ! -f "$STATE_DST" ]; then
    cp "$STATE_SRC" "$STATE_DST"
    echo "[entrypoint] Installed class.State.inc.php from sample"
fi

# Drop in config-test.inc.php for the test suite
if [ ! -f "$CONFIG_TEST_DST" ]; then
    cp "$CONFIG_TEST_SRC" "$CONFIG_TEST_DST"
    echo "[entrypoint] Installed config-test.inc.php from Docker template"
fi

# If the site is behind Cloudflare, take visitors' IP addresses from the CF-Connecting-IP header,
# but only on requests that come from Cloudflare's own addresses, so that nobody else can forge
# it. Off unless TRUSTED_PROXY=cloudflare.
REMOTEIP_CONF="/etc/apache2/conf-enabled/remoteip-cloudflare.conf"
if [ "${TRUSTED_PROXY:-}" = "cloudflare" ]; then
    CF_IPS=$( { curl -fsS --max-time 5 https://www.cloudflare.com/ips-v4 && echo \
                && curl -fsS --max-time 5 https://www.cloudflare.com/ips-v6; } 2>/dev/null \
              | grep -E '^[0-9a-fA-F:.]+/[0-9]+$' || true)
    if [ -z "$CF_IPS" ]; then
        echo "[entrypoint] Could not fetch Cloudflare's IP ranges; using the bundled list"
        CF_IPS=$(grep -E '^[0-9a-fA-F:.]+/[0-9]+$' /var/www/html/deploy/docker/app/cloudflare-ips.txt)
    fi
    {
        echo "# Generated by entrypoint.sh because TRUSTED_PROXY=cloudflare."
        echo "RemoteIPHeader CF-Connecting-IP"
        for range in $CF_IPS; do
            echo "RemoteIPTrustedProxy $range"
        done
    } > "$REMOTEIP_CONF"
    echo "[entrypoint] Trusting CF-Connecting-IP from $(echo "$CF_IPS" | wc -w | tr -d ' ') Cloudflare ranges"
else
    rm -f "$REMOTEIP_CONF"
fi

# Wait for MySQL to accept connections before starting Apache
DB_HOST="${MYSQL_HOST:-db}"
DB_PORT="${MYSQL_PORT:-3306}"
echo "[entrypoint] Waiting for MySQL at ${DB_HOST}:${DB_PORT}..."
until mysqladmin ping -h "$DB_HOST" -P "$DB_PORT" -u "${MYSQL_USER:-statedecoded}" -p"${MYSQL_PASSWORD:-statedecoded}" --skip-ssl --silent 2>/dev/null; do
    sleep 1
done
echo "[entrypoint] MySQL is ready"

exec "$@"
